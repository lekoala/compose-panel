/**
 * Deterministic output for `owner: "managed"` sites (ADR 0042).
 *
 * The manifest is the only input. Re-rendering the same manifest with the same
 * stack directory must produce the same bytes, so drift can be detected by
 * comparison instead of a stored hash. Nothing here reads the filesystem: the
 * caller compares the returned artifacts with what is on disk.
 */
import { posix } from "node:path";
import {
    MANAGED_SITE_CHANNELS,
    MANAGED_SITE_GATEWAY_PORT_MAX,
    MANAGED_SITE_GATEWAY_PORT_MIN,
    MANAGED_SITE_GENERATION,
    MANAGED_SITE_PATHS,
    managedSiteChannel,
    parseManagedSiteManifest,
    type ManagedSiteManifest,
} from "./managed-site.ts";

export const MANAGED_SITE_GATEWAY_IMAGE = "nginx:1.27-alpine";
export const MANAGED_SITE_GATEWAY_CONFIG = "generated/nginx-site.conf";
export const MANAGED_SITE_OPCACHE_CONFIG = "generated/opcache.ini";

export interface ManagedSiteArtifacts {
    compose: string;
    gateway: string;
    opcache: string;
}

export interface ManagedSiteBuildInput {
    /** Canonical absolute stack directory, identical in the panel and on the host. */
    stackDir: string;
    siteId: string;
    project: string;
    port: number;
    gitUrl: string;
    gitRef: string;
    channel: string;
    paths?: string[];
}

export type ManagedSiteBuildResult =
    { ok: true; manifest: ManagedSiteManifest; manifestSource: string; artifacts: ManagedSiteArtifacts } | { ok: false; reason: string };

/**
 * Build the manifest and the generated files for a new managed site. The
 * manifest is parsed back through the strict v1 parser, so this function cannot
 * produce a site the rest of the panel would refuse.
 */
export function buildManagedSite(input: ManagedSiteBuildInput): ManagedSiteBuildResult {
    if (!isCanonicalAbsolute(input.stackDir)) {
        return { ok: false, reason: "A managed site needs a canonical absolute stack directory." };
    }
    const channel = managedSiteChannel(input.channel);
    if (!channel) {
        return {
            ok: false,
            reason: `Choose one of the pinned runtime channels: ${MANAGED_SITE_CHANNELS.map((entry) => entry.id).join(", ")}.`,
        };
    }
    const manifest: Record<string, unknown> = {
        version: 1,
        siteId: input.siteId,
        owner: "managed",
        project: input.project,
        services: { gateway: "gateway", runtime: "runtime" },
        gateway: { port: input.port },
        publicRoot: "public",
        runtime: { profile: "php-front-controller", image: channel.image },
        deploy: { kind: "bind-mount", git: { url: input.gitUrl, ref: input.gitRef } },
        ...(input.paths && input.paths.length > 0 ? { paths: input.paths } : {}),
        generation: MANAGED_SITE_GENERATION,
    };
    const manifestSource = `${JSON.stringify(manifest, null, 2)}\n`;
    const parsed = parseManagedSiteManifest(manifestSource);
    if (!parsed.ok) return parsed;
    if (parsed.manifest.owner !== "managed") return { ok: false, reason: "The generated manifest is not a managed site." };
    return renderManagedSiteArtifacts(input.stackDir, parsed.manifest);
}

/** Render the generated files from an already parsed and validated manifest. */
export function renderManagedSiteArtifacts(
    stackDir: string,
    manifest: ManagedSiteManifest,
): { ok: true; manifest: ManagedSiteManifest; manifestSource: string; artifacts: ManagedSiteArtifacts } | { ok: false; reason: string } {
    if (manifest.owner !== "managed") {
        return { ok: false, reason: "Only a managed site has generated files; an opt-in stack keeps its own Compose file." };
    }
    if (!isCanonicalAbsolute(stackDir)) {
        return { ok: false, reason: "A managed site needs a canonical absolute stack directory." };
    }
    if (manifest.generation !== MANAGED_SITE_GENERATION) {
        return {
            ok: false,
            reason: `This site was generated by version ${manifest.generation ?? "unknown"}, which this panel does not know. It was left unchanged.`,
        };
    }
    if (!manifest.gateway) {
        return { ok: false, reason: "The managed site has no gateway port." };
    }
    const runtimeDir = posix.join(stackDir, MANAGED_SITE_PATHS.runtime);
    const generatedDir = posix.join(stackDir, MANAGED_SITE_PATHS.generated);
    const paths = manifest.paths ?? [];
    const pathMounts = paths
        .map(
            (path) =>
                `      - type: bind\n        source: ${posix.join(stackDir, path)}\n        target: ${posix.join(stackDir, path)}\n        read_only: false`,
        )
        .join("\n");
    const compose = `name: ${manifest.project}

services:
  gateway:
    image: ${MANAGED_SITE_GATEWAY_IMAGE}
    restart: unless-stopped
    depends_on:
      - runtime
    ports:
      - "127.0.0.1:${manifest.gateway.port}:80"
    volumes:
      - type: bind
        source: ${runtimeDir}
        target: ${runtimeDir}
        read_only: true
      - type: bind
        source: ${posix.join(generatedDir, "nginx-site.conf")}
        target: /etc/nginx/conf.d/default.conf
        read_only: true
    networks:
      - site

  runtime:
    image: ${manifest.runtime.image}
    restart: unless-stopped
    volumes:
      - type: bind
        source: ${runtimeDir}
        target: ${runtimeDir}
        read_only: true
      - type: bind
        source: ${posix.join(generatedDir, "opcache.ini")}
        target: /usr/local/etc/php/conf.d/zz-opcache.ini
        read_only: true
${pathMounts ? `${pathMounts}\n` : ""}    networks:
      - site

networks:
  site:
`;
    // The revision probe is outside public/ and reachable only through this
    // exact location. The dotfile rule runs before the PHP rule so the probe
    // script cannot be fetched as .php. Only the front controller executes PHP.
    const gateway = `# Generated for ${manifest.siteId} by Compose Panel. Do not edit: use the manifest and regenerate.
server {
\tlisten 80;
\tserver_name _;

\troot ${runtimeDir}/current/${manifest.publicRoot};
\tindex index.php;

\tlocation = /.compose-panel/revision {
\t\tinclude fastcgi_params;
\t\tfastcgi_param SCRIPT_FILENAME ${runtimeDir}/current/.compose-panel/revision.php;
\t\tfastcgi_pass runtime:9000;
\t}

\tlocation ^~ /.compose-panel/ {
\t\tdeny all;
\t}

\tlocation ~ /\\.(?!well-known) {
\t\tdeny all;
\t}

\tlocation / {
\t\ttry_files $uri $uri/ /index.php?$query_string;
\t}

\tlocation = /index.php {
\t\tinclude fastcgi_params;
\t\tfastcgi_param SCRIPT_FILENAME $document_root/index.php;
\t\tfastcgi_param SCRIPT_NAME /index.php;
\t\tfastcgi_pass runtime:9000;
\t}

\tlocation ~ \\.php$ {
\t\tdeny all;
\t}
}
`;
    const opcache = `; Pinned by Compose Panel: a release switch must be observed by a new
; process, never by a timestamp revalidation.
opcache.enable=1
opcache.enable_cli=0
opcache.validate_timestamps=0
opcache.file_update_protection=0
`;
    return {
        ok: true,
        manifest,
        manifestSource: `${JSON.stringify(serializeManifest(manifest), null, 2)}\n`,
        artifacts: { compose, gateway, opcache },
    };
}

/** Stable field order for the manifest written by the panel. */
function serializeManifest(manifest: ManagedSiteManifest): Record<string, unknown> {
    return {
        version: manifest.version,
        siteId: manifest.siteId,
        owner: manifest.owner,
        project: manifest.project,
        services: { gateway: manifest.services.gateway, runtime: manifest.services.runtime },
        ...(manifest.gateway ? { gateway: { port: manifest.gateway.port } } : {}),
        publicRoot: manifest.publicRoot,
        runtime: {
            profile: manifest.runtime.profile,
            ...(manifest.runtime.image ? { image: manifest.runtime.image } : {}),
        },
        deploy: { kind: manifest.deploy.kind, git: { url: manifest.deploy.git.url, ref: manifest.deploy.git.ref } },
        ...(manifest.paths && manifest.paths.length > 0 ? { paths: manifest.paths } : {}),
        ...(manifest.generation ? { generation: manifest.generation } : {}),
    };
}

function isCanonicalAbsolute(value: string): boolean {
    if (!posix.isAbsolute(value)) return false;
    if (value.length > 1 && value.endsWith("/")) return false;
    if (value.includes("//")) return false;
    // Generated paths are embedded in YAML and in Nginx directives, so a
    // managed stack path is restricted to a conservative character set.
    if (!/^\/(?:[A-Za-z0-9._-]+\/)*[A-Za-z0-9._-]+$/.test(value)) return false;
    return posix.normalize(value) === value;
}

export type ManagedSiteDraft = {
    name: string;
    siteId: string;
    project: string;
    port: number;
    gitUrl: string;
    gitRef: string;
    channel: string;
    paths: string[];
};

export type ManagedSiteDraftResult = { ok: true; draft: ManagedSiteDraft } | { ok: false; reason: string };

/**
 * Validate the creation form. The browser only chooses bounded identifiers and
 * a Git source that the manifest parser validates again; it never supplies a
 * command, a path or an image.
 */
export function parseManagedSiteDraft(form: {
    name: string;
    siteId: string;
    project: string;
    port: string;
    gitUrl: string;
    gitRef: string;
    channel: string;
    paths: string;
}): ManagedSiteDraftResult {
    const name = form.name.trim();
    if (!/^[a-z0-9][a-z0-9_-]{0,62}$/.test(name)) {
        return { ok: false, reason: "The stack name must be lowercase letters, digits, hyphens or underscores, up to 63 characters." };
    }
    const siteId = form.siteId.trim() || name.replaceAll("_", "-");
    if (!/^[a-z0-9][a-z0-9-]{2,63}$/.test(siteId)) {
        return { ok: false, reason: "The site ID must be 3-64 characters of lowercase letters, digits or dashes." };
    }
    const project = form.project.trim() || name;
    if (!/^[a-z0-9][a-z0-9_-]{0,62}$/.test(project)) {
        return { ok: false, reason: "The Compose project must be lowercase letters, digits, hyphens or underscores, up to 63 characters." };
    }
    const portText = form.port.trim();
    if (!/^\d{1,5}$/.test(portText)) {
        return { ok: false, reason: "The gateway port must be a whole number in the reserved managed-site range." };
    }
    const port = Number(portText);
    if (!Number.isInteger(port) || port < MANAGED_SITE_GATEWAY_PORT_MIN || port > MANAGED_SITE_GATEWAY_PORT_MAX) {
        return {
            ok: false,
            reason: `The gateway port must be between ${MANAGED_SITE_GATEWAY_PORT_MIN} and ${MANAGED_SITE_GATEWAY_PORT_MAX}.`,
        };
    }
    const channel = managedSiteChannel(form.channel.trim());
    if (!channel) {
        return { ok: false, reason: "Choose a runtime channel." };
    }
    const paths: string[] = [];
    for (const line of form.paths.split(/\r?\n/)) {
        const path = line.trim();
        if (path.length === 0) continue;
        if (!path.startsWith("shared/") || path.split("/").some((segment) => segment === "" || segment === "." || segment === "..")) {
            return { ok: false, reason: 'Each persistent path must be relative and stay below "shared/".' };
        }
        if (!paths.includes(path)) paths.push(path);
    }
    return {
        ok: true,
        draft: {
            name,
            siteId,
            project,
            port,
            gitUrl: form.gitUrl.trim(),
            gitRef: form.gitRef.trim(),
            channel: channel.id,
            paths,
        },
    };
}
